def set_lang(code):
    LANG['cur'] = 'fa' if code == 'fa' else 'en'


def get_lang():
    return LANG['cur']


def is_fa():
    return LANG['cur'] == 'fa'


def tr(key, **kw):
    pair = STRINGS.get(key)
    if pair is None:
        s = key
    else:
        s = pair[1] if is_fa() else pair[0]
    if kw:
        for k, v in kw.items():
            s = s.replace('{%s}' % k, str(v))
    return s


def T(key, **kw):
    return shape(tr(key, **kw))
